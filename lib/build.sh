# shellcheck shell=bash
# build: get a verified Ubuntu ISO, then build the VM with Packer using only saved settings + Keychain secrets.

_ensure_iso() {
  say "Ubuntu Server $UBUNTU_VERSION (arm64) ISO"
  local base="https://cdimage.ubuntu.com/releases/${UBUNTU_VERSION}/release"
  local name="ubuntu-${UBUNTU_VERSION}-live-server-arm64.iso"
  mkdir -p "$ISO_DIR"

  curl -fsSL "$base/SHA256SUMS" -o "$ISO_DIR/SHA256SUMS" \
    || die "Couldn't fetch $base/SHA256SUMS - is UBUNTU_VERSION ($UBUNTU_VERSION) right?"
  curl -fsSL "$base/SHA256SUMS.gpg" -o "$ISO_DIR/SHA256SUMS.gpg" || die "Couldn't fetch SHA256SUMS.gpg"

  # Verify the checksum list against Ubuntu's signing key in a throwaway keyring.
  # The key is fetched with curl (one process for firewall apps like Little Snitch to allow), falling back to
  # gpg's keyserver lookup. How it arrives doesn't matter: only a signature from this exact fingerprint passes.
  local gnupghome status keyurl attempt
  gnupghome=$(mktemp -d)
  keyurl="https://keyserver.ubuntu.com/pks/lookup?op=get&options=mr&search=0x$UBUNTU_GPG_FPR"
  for attempt in 1 2; do
    if curl -fsSL --retry 2 "$keyurl" -o "$gnupghome/ubuntu.asc" \
       && GNUPGHOME="$gnupghome" gpg --batch --quiet --import "$gnupghome/ubuntu.asc" >/dev/null 2>&1; then
      break
    fi
    if GNUPGHOME="$gnupghome" gpg --batch --quiet --keyserver hkps://keyserver.ubuntu.com \
         --recv-keys "$UBUNTU_GPG_FPR" >/dev/null 2>&1; then
      break
    fi
    if [ "$attempt" = 1 ]; then
      warn "Couldn't fetch Ubuntu's signing key. If a firewall app (e.g. Little Snitch) asked about curl, gpg or dirmngr, allow it."
      pause "Press Enter to try again."
    else
      GNUPGHOME="$gnupghome" gpgconf --kill all >/dev/null 2>&1 || true
      rm -rf "$gnupghome"
      die "Couldn't fetch Ubuntu's signing key ($UBUNTU_GPG_FPR) from keyserver.ubuntu.com"
    fi
  done
  status=$(GNUPGHOME="$gnupghome" gpg --batch --status-fd 1 --verify "$ISO_DIR/SHA256SUMS.gpg" "$ISO_DIR/SHA256SUMS" 2>/dev/null || true)
  GNUPGHOME="$gnupghome" gpgconf --kill all >/dev/null 2>&1 || true
  rm -rf "$gnupghome"
  echo "$status" | grep -q "VALIDSIG $UBUNTU_GPG_FPR" || die "SHA256SUMS signature did NOT verify against Ubuntu's key. Stopping."
  ok "Checksum list signed by Ubuntu ($UBUNTU_GPG_FPR)"

  local sum
  sum=$(awk -v f="$name" '$2 == "*" f || $2 == f {print $1}' "$ISO_DIR/SHA256SUMS")
  [ -n "$sum" ] || die "$name isn't listed in SHA256SUMS - check the version number"

  if [ -z "$ISO_PATH" ]; then ISO_PATH="$ISO_DIR/$name"; fi
  if [ ! -f "$ISO_PATH" ]; then
    info "Downloading $name (about 3 GB)"
    curl -fL --progress-bar "$base/$name" -o "$ISO_PATH.part" || die "Download failed"
    mv "$ISO_PATH.part" "$ISO_PATH"
  fi
  info "Checking the ISO's SHA-256"
  [ "$(shasum -a 256 "$ISO_PATH" | awk '{print $1}')" = "$sum" ] || die "$ISO_PATH does not match Ubuntu's checksum"
  ISO_SHA256=$sum
  save_config
  ok "ISO verified"
}

_write_pkrvars() { # _write_pkrvars ROLE -> path of the generated var file
  local role=$1 f="$BUILD_DIR/$1.pkrvars.hcl" dns="" s cpus mem disk vnc_min
  for s in $DNS_SERVERS; do dns="$dns\"$s\", "; done
  if [ "$role" = router ]; then
    cpus=2; mem=2048; disk=12   # the installer needs 2 GB; it runs with 1 vCPU / 1 GB afterwards
    vnc_min=5950
  else
    cpus=$CPUS; mem=$((MEMORY_GB < 4 ? 4096 : MEMORY_GB * 1024)); disk=$DISK_GB   # the installer wants 4 GB
    vnc_min=5900
  fi
  mkdir -p "$BUILD_DIR"
  cat > "$f" <<EOF
// Generated by hermes-vm.sh from $CONFIG_FILE - re-run 'configure' rather than editing this.
role                = "$role"
vm_name             = "$(vm_name_of "$role")"
output_directory    = "$(vm_dir_of "$role")"
iso_url             = "file://${ISO_PATH// /%20}"
iso_checksum        = "sha256:$ISO_SHA256"
fusion_network      = "nat"   // Fusion default NAT for the build; lockdown moves the VM to its own network
vm_gw               = "$VM_GW"
llm_port            = $LLM_PORT
llm_model           = "$LLM_MODEL"
hermes_image_tag    = "$HERMES_TAG"
cpus                = $cpus
memory_mb           = $mem
disk_size_mb        = $((disk * 1024))
headless            = $HEADLESS
timezone            = "$TIMEZONE"
dns_servers         = [${dns%, }]
admin_username      = "$ADMIN_USER"
vnc_port_min        = $vnc_min
vnc_port_max        = $((vnc_min + 49))
report_dir          = "$BUILD_DIR"
ssh_public_key_file = "$SSH_KEY.pub"
build_ssh_private_key_file = "$BUILD_DIR/build_key"
build_ssh_public_key_file  = "$BUILD_DIR/build_key.pub"
EOF
  echo "$f"
}

_preflight_build() { # _preflight_build [--missing] : sets BUILD_ROLES to the VMs that need building
  [ -f "$FUSION_PREFS/vmnet8/dhcpd.conf" ] || die "Fusion's default NAT network (vmnet8) is missing. Open Fusion > Settings > Network and restore the defaults."
  keychain_has "$ADMIN_USER" || die "No admin password in the Keychain. Run: ./hermes-vm.sh configure"
  [ -f "$SSH_KEY.pub" ] || die "Your SSH public key $SSH_KEY.pub is missing. Run: ./hermes-vm.sh configure"
  local role
  BUILD_ROLES=""
  for role in hermes router; do
    if vm_exists "$role" && [ "${1:-}" = --missing ]; then
      continue
    elif vm_exists "$role"; then
      warn "$(vm_name_of "$role") already exists at $(vm_dir_of "$role")"
      if no_default "Delete it and build a fresh one?"; then
        vm_running "$role" && "$VMRUN" -T fusion stop "$(vmx_path "$role")" hard >/dev/null 2>&1 || true
        "$VMRUN" -T fusion deleteVM "$(vmx_path "$role")" >/dev/null 2>&1 || true
        rm -rf "$(vm_dir_of "$role")"
        BUILD_ROLES="$BUILD_ROLES $role"
      else
        ok "Keeping $(vm_name_of "$role")"
      fi
    else
      BUILD_ROLES="$BUILD_ROLES $role"
    fi
  done
}

_build_intro() { # _build_intro ROLE
  if [ "$1" = router ]; then
    info "The router VM's base Ubuntu install (about 10 minutes)."
  else
    info "The Hermes VM's base Ubuntu install (about 10 minutes). Hardening, Docker and Hermes come next,"
    info "in the 'provision' stage, as separate steps that can be resumed."
  fi
}

# _packer_build ROLE [background]
#   foreground: live output; if a step fails Packer asks what to do (retry with 'r', abort, clean up).
#   background: output to $BUILD_DIR/<role>-build.log, no questions; a failure cleans up so a re-run starts fresh.
# Each build gets its own Packer cache, so two can run at once without touching the same files.
_packer_build() {
  local role=$1 mode=${2:-foreground} vars log
  vars="$BUILD_DIR/$role.pkrvars.hcl"
  log="$BUILD_DIR/$role-build.log"
  if [ "$mode" = background ]; then
    (
      trap - ERR
      cd "$REPO/packer" || exit 1
      PACKER_CACHE_DIR="$BUILD_DIR/packer_cache-$role" \
        packer build -color=false -var-file="$vars" -on-error=cleanup . </dev/null
    ) > "$log" 2>&1
    return
  fi
  if ! (
    cd "$REPO/packer" || exit 1
    PACKER_CACHE_DIR="$BUILD_DIR/packer_cache-$role" packer build -var-file="$vars" -on-error=ask .
  ); then
    if vm_exists "$role"; then
      info "If Packer marked it failed after a successful 'r' retry, the install may be complete. Then:"
      info "  ./hermes-vm.sh post-build $role   and   ./hermes-vm.sh   (it carries on from there)"
    fi
    return 1
  fi
}

_last_log_line() { # the latest meaningful line of a background build's log
  sed -e 's/\x1b\[[0-9;]*m//g' "$1" 2>/dev/null | grep -v '^[[:space:]]*$' | tail -1 | cut -c1-110 || true
}

cmd_build() { # cmd_build [--missing] : stage 1, the base install. --missing builds only VMs that don't exist yet.
  load_config
  export_config
  _preflight_build "${1:-}"
  if [ -z "$BUILD_ROLES" ]; then ok "Both VMs exist; nothing to build. Next: ./hermes-vm.sh"; return 0; fi
  _ensure_iso

  local pw role rpid="" parallel=no last_lines
  # Throwaway SSH key for this build only (Packer can't use a passphrase-protected key). Each VM trusts it only
  # until its build's last step swaps in your real key, and it's deleted from the Mac however the build ends.
  rm -f "$BUILD_DIR/build_key" "$BUILD_DIR/build_key.pub"
  ssh-keygen -q -t ed25519 -N '' -C "hermes-vm-build-$(date +%s)" -f "$BUILD_DIR/build_key"
  trap 'rm -f "$BUILD_DIR/build_key" "$BUILD_DIR/build_key.pub"' EXIT

  pw=$(keychain_get "$ADMIN_USER") || die "Couldn't read the admin password from the Keychain"
  PKR_VAR_admin_password="$pw"
  PKR_VAR_admin_password_hash=$(printf '%s' "$pw" | "$(openssl3)" passwd -6 -stdin)
  export PKR_VAR_admin_password PKR_VAR_admin_password_hash
  pw=""
  export PATH="$FUSION_LIB:$PATH"

  say "Preparing Packer"
  (cd "$REPO/packer" && packer init . >/dev/null) || die "packer init failed"
  for role in $BUILD_ROLES; do
    _write_pkrvars "$role" >/dev/null
    (cd "$REPO/packer" && packer validate -var-file="$BUILD_DIR/$role.pkrvars.hcl" .) >/dev/null \
      || die "Packer rejected the settings for $(vm_name_of "$role"):
$(cd "$REPO/packer" && packer validate -var-file="$BUILD_DIR/$role.pkrvars.hcl" . 2>&1 | head -20)"
  done
  ok "Template and settings valid"

  case " $BUILD_ROLES " in *" hermes "*) case " $BUILD_ROLES " in *" router "*)
    [ "${HERMES_VM_SEQUENTIAL:-0}" = 1 ] || parallel=yes ;; esac ;; esac

  if [ "$parallel" = yes ]; then
    say "Installing both VMs at once"
    info "Hermes installs here, with its output on screen. The router installs alongside it, quietly;"
    info "its progress shows below and its full log is $BUILD_DIR/router-build.log"
    info "(Set HERMES_VM_SEQUENTIAL=1 to build one at a time, e.g. on a Mac with 16 GB or less.)"
    if [ "$HEADLESS" = "false" ]; then
      info "Two Fusion windows will open. Each installer should start by itself after its GRUB menu."
    fi
    _packer_build router background &
    rpid=$!
    say "Building $VM_NAME with Packer"
    _build_intro hermes
    if ! _packer_build hermes; then
      info "Stopping the router build too"
      kill -INT "$rpid" 2>/dev/null || true
      wait "$rpid" 2>/dev/null || true
      unset PKR_VAR_admin_password PKR_VAR_admin_password_hash
      die "Packer build of $VM_NAME failed"
    fi
    _post_build hermes
    if kill -0 "$rpid" 2>/dev/null; then
      say "Waiting for the router build to finish"
      while kill -0 "$rpid" 2>/dev/null; do
        info "router: $(_last_log_line "$BUILD_DIR/router-build.log")"
        sleep 60
      done
    fi
    if wait "$rpid"; then
      ok "Router build finished ($BUILD_DIR/router-build.log)"
      _post_build router
    else
      warn "The router build failed. The end of its log:"
      last_lines=$(sed -e 's/\x1b\[[0-9;]*m//g' "$BUILD_DIR/router-build.log" | tail -25)
      printf '%s\n' "$last_lines" | sed 's/^/      /' >&2
      unset PKR_VAR_admin_password PKR_VAR_admin_password_hash
      die "Packer build of $ROUTER_NAME failed. Hermes is built; re-run ./hermes-vm.sh build to retry just the router."
    fi
  else
    for role in $BUILD_ROLES; do
      say "Building $(vm_name_of "$role") with Packer"
      _build_intro "$role"
      if [ "$HEADLESS" = "false" ]; then
        info "Watch the Fusion window: the installer should start by itself after the GRUB menu."
        info "If it stops at a language screen instead, see 'Installer goes interactive' in the README."
      fi
      if ! _packer_build "$role"; then
        unset PKR_VAR_admin_password PKR_VAR_admin_password_hash
        die "Packer build of $(vm_name_of "$role") failed"
      fi
      _post_build "$role"
    done
  fi
  unset PKR_VAR_admin_password PKR_VAR_admin_password_hash
  rm -f "$BUILD_DIR/build_key" "$BUILD_DIR/build_key.pub"
}

cmd_post_build() { # cmd_post_build [hermes|router]
  local role=${1:-hermes}
  case "$role" in hermes|router) ;; *) die "post-build takes hermes or router" ;; esac
  load_config
  vm_exists "$role" || die "No VM at $(vm_dir_of "$role") to finish. Run: ./hermes-vm.sh build"
  vm_running "$role" && die "Shut it down first: ./hermes-vm.sh stop"
  _post_build "$role"
}

_post_build() { # _post_build ROLE
  local role=$1 vmx dev
  say "Finishing $(vm_name_of "$role")'s base install"
  vmx=$(vmx_path "$role")
  [ -f "$vmx" ] || die "Packer finished but $vmx is missing"

  # Detach every CD/DVD device (installer ISO, cidata, VMware Tools).
  for dev in $(grep -iE '^[a-z0-9]+:[0-9]+\.devicetype = "(cdrom-image|cdrom-raw|atapi-cdrom)"' "$vmx" | cut -d. -f1 | tr 'A-Z' 'a-z' | sort -u || true); do
    vmx_set "$vmx" "$dev.present" FALSE
  done
  ok "Installer media detached"

  # Packer uses VNC to type the boot command; make sure it's off for good.
  vmx_del "$vmx" 'remotedisplay\.vnc\.[a-z0-9.]+'
  printf 'RemoteDisplay.vnc.enabled = "FALSE"\n' >> "$vmx"
  ok "VNC console disabled"

  forget_host_key "$role"
  _snapshot "$role" base
  ok "Snapshot 'base' taken (Ubuntu installed, nothing else yet)"
  return 0
}

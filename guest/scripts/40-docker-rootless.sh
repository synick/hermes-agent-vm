#!/usr/bin/env bash
# 40-docker-rootless.sh - Docker Engine in rootless mode for a dedicated, sudo-less 'hermes' user.
# No root daemon, no root socket: a compromised container (or the Docker socket) is worth 'hermes', not root.
set -euo pipefail
export DEBIAN_FRONTEND=noninteractive NEEDRESTART_MODE=a
F=/var/tmp/hermes-files
log() { echo "==> [40-docker] $*"; }

log "Docker apt repository"
install -m 0755 -d /etc/apt/keyrings
curl -fsSL https://download.docker.com/linux/ubuntu/gpg -o /etc/apt/keyrings/docker.asc
chmod a+r /etc/apt/keyrings/docker.asc
. /etc/os-release
echo "deb [arch=$(dpkg --print-architecture) signed-by=/etc/apt/keyrings/docker.asc] https://download.docker.com/linux/ubuntu ${VERSION_CODENAME} stable" \
  > /etc/apt/sources.list.d/docker.list
apt-get update
apt-get -y install docker-ce docker-ce-cli containerd.io docker-ce-rootless-extras docker-compose-plugin slirp4netns

log "Loading the nf_tables kernel module (Docker networking needs it; also loaded at every boot)"
modprobe nf_tables
echo nf_tables > /etc/modules-load.d/hermes-docker.conf

log "Disabling the rootful daemon and removing its socket"
systemctl disable --now docker.service docker.socket containerd.service 2>/dev/null || true
rm -f /var/run/docker.sock

log "Creating the 'hermes' user (no sudo, no password, no SSH)"
if ! id hermes >/dev/null 2>&1; then
  useradd --create-home --shell /bin/bash --comment "Hermes agent" hermes
fi
passwd -l hermes
chmod 0750 /home/hermes
grep -q '^hermes:' /etc/subuid || usermod --add-subuids 100000-165535 --add-subgids 100000-165535 hermes

HUID="$(id -u hermes)"
loginctl enable-linger hermes
systemctl start "user@${HUID}.service"
as_hermes() {
  sudo -iu hermes env XDG_RUNTIME_DIR="/run/user/${HUID}" \
    DBUS_SESSION_BUS_ADDRESS="unix:path=/run/user/${HUID}/bus" "$@"
}

log "Making sure 'hermes' can create user namespaces (needed by rootless Docker)"
# Ubuntu restricts unprivileged user namespaces via AppArmor (kernel.apparmor_restrict_unprivileged_userns=1)
# unless the program has a profile allowing them. Newer Ubuntu releases may already ship one for rootlesskit;
# adding a second profile for the same binary makes AppArmor refuse to run it ("permission denied").
# So: clear anything earlier attempts added, test as-is, and add our own profile only if it's really needed.
RK_CMD="$(command -v rootlesskit || true)"
[ -n "$RK_CMD" ] || { echo "ERROR: rootlesskit not found after installing docker-ce-rootless-extras" >&2; exit 1; }
RK_REAL="$(readlink -f "$RK_CMD")"
RK_PROFILE="/etc/apparmor.d/hermes-rootlesskit"
AA_PROFILES=/sys/kernel/security/apparmor/profiles

aa_unload() { # unload a profile by name if loaded
  if grep -q "^$1 (" "$AA_PROFILES" 2>/dev/null; then
    printf '%s' "$1" > /sys/kernel/security/apparmor/.remove 2>/dev/null || true
  fi
}
rk_works() { as_hermes rootlesskit true >/dev/null 2>&1; }

rm -f /etc/apparmor.d/usr.bin.rootlesskit "$RK_PROFILE"
aa_unload "/usr/bin/rootlesskit"      # from an earlier hermes-vm attempt
aa_unload "hermes-rootlesskit"        # from an earlier hermes-vm attempt

if rk_works; then
  echo "    rootlesskit works with the system's own AppArmor policy; no extra profile needed"
else
  echo "    rootlesskit blocked as-is; adding a dedicated AppArmor profile for $RK_REAL"
  {
    echo "# Generated by hermes-vm 40-docker-rootless.sh: lets rootless Docker create user namespaces."
    echo "abi <abi/4.0>,"
    echo "include <tunables/global>"
    echo ""
    echo "profile hermes-rootlesskit ${RK_REAL} flags=(unconfined) {"
    echo "  userns,"
    echo "  include if exists <local/hermes-rootlesskit>"
    echo "}"
  } > "$RK_PROFILE"
  chmod 0644 "$RK_PROFILE"
  apparmor_parser -r "$RK_PROFILE"
  if ! rk_works; then
    echo "ERROR: rootlesskit still can't create a user namespace as 'hermes'. Diagnostics:" >&2
    echo "  rootlesskit:            $RK_CMD -> $RK_REAL" >&2
    echo "  restrict_userns:        $(cat /proc/sys/kernel/apparmor_restrict_unprivileged_userns 2>/dev/null || echo n/a)" >&2
    echo "  max_user_namespaces:    $(cat /proc/sys/user/max_user_namespaces 2>/dev/null || echo n/a)" >&2
    echo "  subuid entry:           $(grep '^hermes:' /etc/subuid || echo none)" >&2
    echo "  newuidmap:              $(ls -l "$(command -v newuidmap)" 2>/dev/null || echo missing)" >&2
    echo "  AppArmor profiles mentioning rootlesskit:" >&2
    grep -i rootlesskit "$AA_PROFILES" >&2 || echo "    (none)" >&2
    grep -ril rootlesskit /etc/apparmor.d 2>/dev/null | sed 's/^/    file: /' >&2 || true
    echo "  Recent AppArmor denials (audit log, then kernel log):" >&2
    { grep -h 'apparmor="DENIED"' /var/log/audit/audit.log 2>/dev/null; journalctl -k --no-pager -n 500 2>/dev/null | grep 'apparmor="DENIED"'; } | tail -6 >&2 || true
    exit 1
  fi
  echo "    rootlesskit works with the hermes-rootlesskit profile"
fi

log "Installing rootless Docker for 'hermes'"
# Clear any half-finished attempt first (e.g. a Packer retry after a failure here), including our daemon.json:
# the installer starts Docker with whatever settings file it finds, and ours is applied afterwards anyway.
as_hermes dockerd-rootless-setuptool.sh uninstall -f >/dev/null 2>&1 || true
as_hermes rootlesskit rm -rf /home/hermes/.local/share/docker >/dev/null 2>&1 || true
rm -f /home/hermes/.config/docker/daemon.json
if ! as_hermes dockerd-rootless-setuptool.sh install --force; then
  echo "ERROR: the rootless Docker installer couldn't start Docker. Its log:" >&2
  as_hermes journalctl --user -u docker --no-pager -n 25 >&2 2>/dev/null || true
  exit 1
fi

log "Rootless daemon config"
# Applies no-new-privileges and capped local logs. If the daemon won't start with them, show Docker's own error,
# then fall back to logging-only, then to Docker's defaults, so a settings problem never sinks the whole build.
DJSON=/home/hermes/.config/docker/daemon.json
install -d -o hermes -g hermes -m 0700 /home/hermes/.config/docker
as_hermes systemctl --user enable docker >/dev/null 2>&1 || true

apply_daemon_json() { # apply_daemon_json "<label>" <file or "">
  if [ -n "$2" ]; then install -o hermes -g hermes -m 0600 "$2" "$DJSON"; else rm -f "$DJSON"; fi
  if as_hermes systemctl --user restart docker && sleep 3 && as_hermes systemctl --user is-active --quiet docker; then
    echo "    Docker daemon running with: $1"; return 0
  fi
  echo "WARNING: rootless Docker wouldn't start with: $1. Its log:" >&2
  as_hermes journalctl --user -u docker --no-pager -n 15 >&2 2>/dev/null || true
  return 1
}

LOGONLY="$(mktemp)"
printf '{\n  "log-driver": "local",\n  "log-opts": { "max-size": "20m", "max-file": "5" }\n}\n' > "$LOGONLY"
apply_daemon_json "no-new-privileges + capped logs" "$F/docker/daemon.json" \
  || apply_daemon_json "capped logs only (no-new-privileges still set per container in compose.yaml)" "$LOGONLY" \
  || apply_daemon_json "Docker defaults" "" \
  || { echo "ERROR: rootless Docker won't start even with default settings (log above)" >&2; exit 1; }
rm -f "$LOGONLY"

for rc in /home/hermes/.profile /home/hermes/.bashrc; do
  grep -q 'DOCKER_HOST' "$rc" 2>/dev/null || \
    echo 'export DOCKER_HOST=unix:///run/user/$(id -u)/docker.sock' >> "$rc"
done

log "Verifying rootless mode"
as_hermes env DOCKER_HOST="unix:///run/user/${HUID}/docker.sock" \
  docker info --format '{{.SecurityOptions}}' | grep -q rootless
log "Done - rootless Docker running as hermes (uid ${HUID})"
